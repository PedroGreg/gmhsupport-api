-- ----- Técnico: dados do cadastro e situação da análise -----
ALTER TABLE tecnicos ALTER COLUMN especialidade SET DATA TYPE VARCHAR(500);
ALTER TABLE tecnicos ADD COLUMN cpf VARCHAR(11) UNIQUE;
ALTER TABLE tecnicos ADD COLUMN telefone VARCHAR(20);
ALTER TABLE tecnicos ADD COLUMN data_nascimento DATE;
ALTER TABLE tecnicos ADD COLUMN chave_pix VARCHAR(150);
-- pendente = aguardando o admin | aprovado = pode atender | recusado = ver motivo e reenviar
ALTER TABLE tecnicos ADD COLUMN status_cadastro VARCHAR(20) DEFAULT 'pendente' NOT NULL
    CHECK (status_cadastro IN ('pendente', 'aprovado', 'recusado'));
ALTER TABLE tecnicos ADD COLUMN motivo_recusa VARCHAR(500);
ALTER TABLE tecnicos ADD COLUMN termos_aceitos_em TIMESTAMP;
ALTER TABLE tecnicos ADD COLUMN data_analise TIMESTAMP;

-- Os técnicos que já existiam continuam aprovados
UPDATE tecnicos SET status_cadastro = 'aprovado', data_analise = CURRENT_TIMESTAMP;

-- ----- Certidão de antecedentes criminais (1 por técnico; reenviar substitui) -----
CREATE TABLE documentos_tecnico (
    id_documento   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tecnico     BIGINT NOT NULL UNIQUE REFERENCES tecnicos(id_tecnico) ON DELETE CASCADE,
    nome_arquivo   VARCHAR(255) NOT NULL,
    tipo_conteudo  VARCHAR(100) NOT NULL,
    tamanho        BIGINT NOT NULL,
    conteudo       BYTEA NOT NULL,
    data_envio     TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ----- Administradores: senha + código do Google Authenticator (TOTP) -----
CREATE TABLE administradores (
    id_admin            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(150) NOT NULL,
    email               VARCHAR(150) NOT NULL UNIQUE,
    senha               VARCHAR(255) NOT NULL,
    totp_segredo        VARCHAR(64),
    totp_ativo          BOOLEAN DEFAULT FALSE NOT NULL,
    ultimo_passo_totp   BIGINT,
    tentativas_falhas   INTEGER DEFAULT 0 NOT NULL,
    bloqueado_ate       TIMESTAMP,
    data_cadastro       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ----- Repasse ao técnico (por pagamento) -----
-- nao_liberado = serviço ainda não concluído | liberado = admin precisa pagar | pago = Pix enviado ao técnico
ALTER TABLE pagamentos ADD COLUMN repasse_status VARCHAR(20) DEFAULT 'nao_liberado' NOT NULL
    CHECK (repasse_status IN ('nao_liberado', 'liberado', 'pago'));
ALTER TABLE pagamentos ADD COLUMN valor_repasse NUMERIC(10,2);
ALTER TABLE pagamentos ADD COLUMN data_repasse_liberado TIMESTAMP;
ALTER TABLE pagamentos ADD COLUMN data_repasse_pago TIMESTAMP;
ALTER TABLE pagamentos ADD COLUMN observacao_repasse VARCHAR(255);

-- Chamados já resolvidos e pagos antes desta versão: repasse liberado (80%)
UPDATE pagamentos SET repasse_status = 'liberado',
                      valor_repasse = ROUND(valor * 0.80, 2),
                      data_repasse_liberado = CURRENT_TIMESTAMP
 WHERE status = 'pago'
   AND id_chamado IN (SELECT id_chamado FROM chamados WHERE id_status = 4);

CREATE INDEX idx_tecnicos_status_cadastro ON tecnicos(status_cadastro);
CREATE INDEX idx_pagamentos_repasse ON pagamentos(repasse_status);
