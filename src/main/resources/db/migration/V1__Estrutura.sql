-- =====================================================================
-- GMH Support · estrutura do banco (PostgreSQL)
-- Também roda no H2 local em MODE=PostgreSQL.
-- Os "enums" são VARCHAR com CHECK, para funcionar igual nos dois bancos.
-- =====================================================================

CREATE TABLE usuarios (
    id_usuario     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    senha          VARCHAR(255) NOT NULL,
    telefone       VARCHAR(20),
    endereco       VARCHAR(255),
    data_cadastro  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tecnicos (
    id_tecnico     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome           VARCHAR(150) NOT NULL,
    email          VARCHAR(150) NOT NULL UNIQUE,
    senha          VARCHAR(255) NOT NULL,
    especialidade  VARCHAR(100),
    disponivel     BOOLEAN NOT NULL DEFAULT TRUE,
    data_cadastro  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Categoria = grupo (Hardware, Software...). valor_fixo = TRUE: sem acréscimo de prioridade nem de km (ex.: Testes)
CREATE TABLE categorias_problema (
    id_categoria  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome          VARCHAR(100) NOT NULL,
    descricao     VARCHAR(255),
    valor_fixo    BOOLEAN NOT NULL DEFAULT FALSE
);

-- Subcategoria = o problema em si, com o preço base do atendimento
CREATE TABLE subcategorias_problema (
    id_subcategoria  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria     BIGINT NOT NULL REFERENCES categorias_problema(id_categoria),
    nome             VARCHAR(120) NOT NULL,
    descricao        VARCHAR(255),
    valor_base       NUMERIC(10,2) NOT NULL,
    ativo            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE status_chamado (
    id_status  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao  VARCHAR(50) NOT NULL
);

CREATE TABLE chamados (
    id_chamado            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario            BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    id_tecnico            BIGINT REFERENCES tecnicos(id_tecnico),
    id_categoria          BIGINT REFERENCES categorias_problema(id_categoria),
    id_subcategoria       BIGINT REFERENCES subcategorias_problema(id_subcategoria),
    id_status             BIGINT NOT NULL DEFAULT 1 REFERENCES status_chamado(id_status),
    titulo                VARCHAR(150) NOT NULL,
    descricao             VARCHAR(4000) NOT NULL,
    prioridade            VARCHAR(10) NOT NULL DEFAULT 'media'
                          CHECK (prioridade IN ('baixa', 'media', 'alta', 'urgente')),
    -- Local do atendimento (informado pelo cliente: GPS ou endereço digitado)
    endereco_atendimento  VARCHAR(255),
    complemento           VARCHAR(120),
    latitude              DOUBLE PRECISION,
    longitude             DOUBLE PRECISION,
    distancia_km          NUMERIC(6,2),
    -- Código de confirmação para finalizar (o cliente vê, o técnico digita)
    codigo_confirmacao    VARCHAR(6),
    codigo_expira_em      TIMESTAMP,
    codigo_tentativas     INT NOT NULL DEFAULT 0,
    solucao               VARCHAR(4000),
    data_abertura         TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_atendimento      TIMESTAMP,
    data_fechamento       TIMESTAMP
);

CREATE TABLE historico_chamado (
    id_historico   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chamado     BIGINT NOT NULL REFERENCES chamados(id_chamado),
    id_tecnico     BIGINT REFERENCES tecnicos(id_tecnico),
    id_usuario     BIGINT REFERENCES usuarios(id_usuario),
    descricao      VARCHAR(4000) NOT NULL,
    data_registro  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE avaliacoes (
    id_avaliacao    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chamado      BIGINT NOT NULL UNIQUE REFERENCES chamados(id_chamado),
    nota            INT NOT NULL CHECK (nota BETWEEN 0 AND 5),
    comentario      VARCHAR(4000),
    data_avaliacao  TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Cartões salvos (só dados de exibição: nunca o número completo nem o CVV)
CREATE TABLE cartoes (
    id_cartao        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario       BIGINT NOT NULL REFERENCES usuarios(id_usuario),
    apelido          VARCHAR(40),
    tipo             VARCHAR(10) NOT NULL CHECK (tipo IN ('credito', 'debito')),
    bandeira         VARCHAR(20) NOT NULL,
    ultimos_digitos  VARCHAR(4) NOT NULL,
    nome_titular     VARCHAR(100) NOT NULL,
    mes_validade     INT NOT NULL,
    ano_validade     INT NOT NULL,
    principal        BOOLEAN NOT NULL DEFAULT FALSE,
    data_cadastro    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Pagamentos: o "principal" (na abertura) e, se houver, o "adicional" pedido pelo técnico
CREATE TABLE pagamentos (
    id_pagamento        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chamado          BIGINT NOT NULL REFERENCES chamados(id_chamado),
    tipo                VARCHAR(20) NOT NULL DEFAULT 'principal' CHECK (tipo IN ('principal', 'adicional')),
    valor               NUMERIC(10,2) NOT NULL,
    valor_servico       NUMERIC(10,2),
    valor_deslocamento  NUMERIC(10,2),
    status              VARCHAR(20) NOT NULL DEFAULT 'pendente'
                        CHECK (status IN ('pendente', 'aguardando_pix', 'pago', 'estornado')),
    forma               VARCHAR(20) CHECK (forma IN ('pix', 'credito', 'debito')),
    parcelas            INT,
    cartao_final        VARCHAR(4),
    bandeira            VARCHAR(20),
    codigo_pix          VARCHAR(255),
    data_criacao        TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_pagamento      TIMESTAMP,
    CONSTRAINT uk_pagamento_chamado_tipo UNIQUE (id_chamado, tipo)
);

-- Valor adicional pedido pelo técnico (no máximo 1 por chamado)
CREATE TABLE adicionais (
    id_adicional      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_chamado        BIGINT NOT NULL UNIQUE REFERENCES chamados(id_chamado),
    id_tecnico        BIGINT NOT NULL REFERENCES tecnicos(id_tecnico),
    valor             NUMERIC(10,2) NOT NULL,
    motivo            VARCHAR(1000) NOT NULL,
    status            VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'aceito', 'recusado')),
    decisao_tecnico   VARCHAR(20) CHECK (decisao_tecnico IN ('continuar', 'cancelar')),
    data_solicitacao  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    data_resposta     TIMESTAMP
);

CREATE INDEX idx_chamados_usuario ON chamados(id_usuario);
CREATE INDEX idx_chamados_tecnico ON chamados(id_tecnico);
CREATE INDEX idx_historico_chamado ON historico_chamado(id_chamado);
CREATE INDEX idx_subcategorias_categoria ON subcategorias_problema(id_categoria);
